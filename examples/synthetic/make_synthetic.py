#!/usr/bin/env python
"""Generate a tiny, FULLY SYNTHETIC example corpus.

The synthetic example data are provided solely to demonstrate the software interface and
pipeline.  They do not reproduce, approximate, or derive from the proprietary BRGM
well-log data used in the study, and they neither reconstruct nor statistically reproduce
it in any respect.

Concretely, the generator uses deliberately artificial construction: each "log" is a sum
of a handful of sine waves plus white noise, on a round depth range, with values forced
into obviously synthetic ranges.  No statistic of the real corpus -- no mean, variance,
correlation, gap-length distribution, well count, depth coverage or coordinate -- is used
anywhere.  Wells are named ``SYN01 .. SYN06`` and placed on a regular grid of round
coordinates.

What it writes (into ``examples/synthetic/data/``):

``las/*.las``                    a minimal LAS 2.0 file per well, to exercise the reader
``processed/well_logs.npz``      the pipeline's own output format
``processed/slices.npz``
``processed/folds_loo.json``
``processed/well_coordinates.csv``  the coordinate table the spatial models need

Usage:
    python examples/synthetic/make_synthetic.py [--out DIR] [--wells 6] [--seed 0]
"""
import argparse
import json
import os

import numpy as np

N_LOGS = 3
LOG_NAMES = ["GR", "RHOB", "NPHI"]
LOG_UNITS = ["GAPI", "G/C3", "V/V"]
STEP = 0.1524          # the depth step the pipeline expects (0.5 ft)


def synth_well(rng, n, phase):
    """Three obviously artificial curves: a few sines plus noise, in plausible ranges."""
    t = np.arange(n) * STEP
    def wave(scale, periods, offset):
        s = sum(np.sin(2 * np.pi * t / p + phase * (i + 1)) for i, p in enumerate(periods))
        return offset + scale * s / len(periods)
    gr = wave(40.0, [37.0, 113.0, 401.0], 80.0) + rng.normal(0, 3.0, n)
    rhob = wave(0.25, [53.0, 211.0], 2.45) + rng.normal(0, 0.02, n)
    nphi = wave(0.10, [61.0, 173.0], 0.25) + rng.normal(0, 0.01, n)
    # clip into the physical bounds the pipeline enforces, so nothing is silently dropped
    gr = np.clip(gr, 1.0, 399.0)
    rhob = np.clip(rhob, 1.25, 3.05)
    nphi = np.clip(nphi, 0.0, 0.95)
    return np.stack([gr, rhob, nphi], axis=1)


def write_las(path, well, depth, arr):
    """Minimal LAS 2.0 file, enough for lasio and for the data pipeline."""
    lines = [
        "~Version Information",
        "VERS.   2.0 : CWLS LOG ASCII STANDARD - VERSION 2.0",
        "WRAP.    NO : ONE LINE PER DEPTH STEP",
        "~Well Information",
        "STRT.M {:.4f} : START DEPTH".format(depth[0]),
        "STOP.M {:.4f} : STOP DEPTH".format(depth[-1]),
        "STEP.M {:.4f} : STEP".format(STEP),
        "NULL.  -999.25 : NULL VALUE",
        "WELL.  {} : WELL".format(well),
        "~Curve Information",
        "DEPT.M    : DEPTH",
    ]
    for nm, un in zip(LOG_NAMES, LOG_UNITS):
        lines.append(f"{nm}.{un}    : {nm}")
    lines.append("~Other")
    lines.append("SYNTHETIC DATA - generated by examples/synthetic/make_synthetic.py.")
    lines.append("Does not reproduce, approximate or derive from any real well log.")
    lines.append("~ASCII")
    for i, d in enumerate(depth):
        lines.append("{:10.4f} {:10.4f} {:10.4f} {:10.4f}".format(
            d, arr[i, 0], arr[i, 1], arr[i, 2]))
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "data"))
    ap.add_argument("--wells", type=int, default=6)
    ap.add_argument("--samples", type=int, default=900, help="depth samples per well")
    ap.add_argument("--slice", type=int, default=256)
    ap.add_argument("--stride", type=int, default=64)
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()

    las_dir = os.path.join(args.out, "las")
    proc_dir = os.path.join(args.out, "processed")
    os.makedirs(las_dir, exist_ok=True)
    os.makedirs(proc_dir, exist_ok=True)
    rng = np.random.default_rng(args.seed)

    wells = [f"SYN{i+1:02d}" for i in range(args.wells)]
    logs_by_well, X, meta = {}, [], []
    for wi, w in enumerate(wells):
        n = args.samples
        depth = 100.0 + np.arange(n) * STEP          # a round, artificial start depth
        arr = synth_well(rng, n, phase=0.7 * wi)
        logs_by_well[w] = np.concatenate([depth[:, None], arr], axis=1)   # (L,4)
        write_las(os.path.join(las_dir, f"{w}.las"), w, depth, arr)
        s = 0
        while s + args.slice <= n:
            X.append(arr[s:s+args.slice])
            meta.append((w, s))
            s += args.stride

    X = np.asarray(X, dtype=np.float32)
    np.savez_compressed(os.path.join(proc_dir, "well_logs.npz"),
                        **logs_by_well, logs=np.array(["depth"] + LOG_NAMES))
    np.savez_compressed(os.path.join(proc_dir, "slices.npz"),
                        X=X,
                        wells=np.array([m[0] for m in meta]),
                        starts=np.array([m[1] for m in meta]),
                        logs=np.array(LOG_NAMES),
                        slice_len=args.slice, stride=args.stride)
    folds = {f"fold_{i}": {"test": [w], "train": [x for x in wells if x != w]}
             for i, w in enumerate(wells)}
    with open(os.path.join(proc_dir, "folds_loo.json"), "w") as f:
        json.dump({"wells": wells, "n_folds": len(wells), "folds": folds}, f, indent=2)

    # Coordinates on a regular grid of round numbers -- no relation to any real location.
    with open(os.path.join(proc_dir, "well_coordinates.csv"), "w") as f:
        f.write("Name,SIGLE,Surf_LocX_L93,Surf_LocY_L93\n")
        for i, w in enumerate(wells):
            x = 100000.0 + 2000.0 * (i % 3)
            y = 200000.0 + 2000.0 * (i // 3)
            f.write(f"{w},{w},{x:.1f},{y:.1f}\n")

    print(f"Synthetic corpus written to {args.out}")
    print(f"  wells   : {len(wells)}  ({', '.join(wells)})")
    print(f"  windows : {len(X)} of length {args.slice} (stride {args.stride})")
    print(f"  LAS     : {las_dir}")
    print(f"  arrays  : {proc_dir}")


if __name__ == "__main__":
    main()
